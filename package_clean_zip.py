import os
import zipfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent
ZIP_PATH = PROJECT_ROOT / "Celestia_Clean.zip"

EXCLUDE_DIRS = {
    ".git",
    ".venv",
    "venv",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".system_generated",
}

EXCLUDE_FILES = {
    ".env",
    "Celestia_Clean.zip",
    "package_clean_zip.py",
}

# Keep only 2 days of sample raw data so the reviewer has immediate sample data
SAMPLE_DATES = {"20261101", "20261102"}

def make_zip():
    if ZIP_PATH.exists():
        ZIP_PATH.unlink()

    with zipfile.ZipFile(ZIP_PATH, "w", zipfile.ZIP_DEFLATED) as zf:
        for root, dirs, files in os.walk(PROJECT_ROOT):
            # Prune excluded directories in-place
            dirs[:] = [d for d in dirs if d not in EXCLUDE_DIRS and not d.startswith(".")]

            for file in files:
                if file in EXCLUDE_FILES or file.startswith(".env") and file != ".env.example":
                    continue
                if file.endswith(".pyc") or file.endswith(".pyo"):
                    continue

                full_path = Path(root) / file
                rel_path = full_path.relative_to(PROJECT_ROOT)
                parts = rel_path.parts

                # Handle data directories: keep .gitkeep and selected sample dates only
                if len(parts) > 1 and parts[0] == "data":
                    if parts[1] == "processed":
                        if file != ".gitkeep":
                            continue  # Pipeline outputs are regenerated by backfill_history.py
                    elif parts[1] == "raw":
                        if file != ".gitkeep" and not any(d in file for d in SAMPLE_DATES):
                            continue  # Keep sample raw files for 2026-11-01 & 2026-11-02

                zf.write(full_path, rel_path.as_posix())

    size_mb = ZIP_PATH.stat().st_size / (1024 * 1024)
    print(f"Clean archive created: {ZIP_PATH} ({size_mb:.2f} MB)")

if __name__ == "__main__":
    make_zip()

